# Feature: predictive-forecasting-agent, Property 6: Tool-call retry and timeout behavior
@PROPERTY_SETTINGS
@given(
    occupancy_outcomes=_outcome_sequence,
    revenue_outcomes=_outcome_sequence,
)
def test_property_6_tool_call_retry_and_timeout(
    occupancy_outcomes: list[str],
    revenue_outcomes: list[str],
) -> None:
    """Retry loop: <=3 attempts, stops on first success, timeout == failed attempt.

    For independently generated per-tool outcome sequences (occupancy and
    revenue, ``needs_overflow=False`` to keep the read to Phase 1), asserts:

    - No tool makes more than ``MAX_ATTEMPTS`` (3) attempts.
    - The loop STOPS on the first success: attempts consumed equal the prefix up
      to and including the first success (nothing after a success runs).
    - A timeout is treated as a failed attempt: it triggers a retry just like a
      ``fail`` (a sequence like ``[timeout, success]`` still succeeds on the 2nd
      attempt), which the attempt-count and success-derivation checks capture.
    - The backoff seconds slept before each retry match the prefix of
      ``BACKOFF_SEQUENCE_SECONDS`` == (1.0, 2.0): sleep(1.0) after the 1st failed
      attempt, sleep(2.0) after the 2nd; no sleep after a success or after the
      final attempt.
    """
    # Pad each sequence to MAX_ATTEMPTS so the fake has a defined outcome for
    # every attempt the reader might make (it retries non-successes up to 3).
    sequences = {
        TOOL_GET_OCCUPANCY: _pad_to_max_attempts(occupancy_outcomes),
        TOOL_GET_REVENUE: _pad_to_max_attempts(revenue_outcomes),
    }
    fake = StatefulToolFake(sequences)

    result = read_signals(
        RUN_PROPERTY_ID,
        _horizon(),
        fake.call_tool,
        needs_overflow=False,
        timeout_runner=fake.timeout_runner,
        sleep=fake.sleep,
    )

    for tool_name in OCCUPANCY_REVENUE_TOOLS:
        outcomes = sequences[tool_name]
        expected_consumed = _truncate_after_first_success(outcomes)
        attempts_made = fake.attempts[tool_name]

        # No tool exceeds MAX_ATTEMPTS (3) attempts.
        assert attempts_made <= MAX_ATTEMPTS

        # The loop stops on the first success: attempts consumed equal the prefix
        # up to and including the first success (or the whole sequence when none
        # succeeds). This also encodes "timeout is a failed attempt" - a timeout
        # is NOT a stop, only a success is.
        assert attempts_made == len(expected_consumed)

        # If the consumed prefix ended in a success, no attempt ran after it.
        succeeded = expected_consumed[-1] == OUTCOME_SUCCESS
        if succeeded:
            assert expected_consumed.count(OUTCOME_SUCCESS) == 1

        # A tool that never succeeds is degraded gracefully into missing_signals
        # (and its consumed attempts are the full capped sequence).
        if not succeeded:
            assert tool_name in result.missing_signals
        else:
            assert tool_name not in result.missing_signals

        # Backoff: one sleep before each retry, so the number of sleeps is the
        # number of consumed attempts minus one, and never more than the two
        # available backoff gaps.
        expected_sleeps = list(BACKOFF_SEQUENCE_SECONDS[: len(expected_consumed) - 1])
        assert fake.sleeps[tool_name] == expected_sleeps
        assert BACKOFF_SEQUENCE_SECONDS == (1.0, 2.0)

    # A [timeout, success] style sequence must succeed on the 2nd attempt: no
    # tool that ends in success is reported missing (checked above per tool).
